package com.example.meal_app.constant;

/**
 * This interface defines constants for database column names. These constants
 * can be used throughout the application to avoid hardcoding column names.
 */
public interface DBConstants {

    // Column name for the unique identifier of a record
    public static final String ID_COL = "id";

    // Column name for the username
    public static final String USER_NAME_COL = "username";

    // Column name for the email address
    public static final String EMAIL_COL = "email";

    // Column name for the password
    public static final String PASSWORD_COL = "password";

}
